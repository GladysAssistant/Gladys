const asyncMiddleware = require('../../../api/middlewares/asyncMiddleware');
const logger = require('../../../utils/logger');
const { BadParameters } = require('../../../utils/coreErrors');
const { ADAPTER_MODE } = require('../lib/constants');

module.exports = function Zigbee2mqttController(gladys, zigbee2mqttManager) {
  /**
   * @description Refuse to start a container of the integration while the user keeps Zigbee2mqtt stopped: only the
   * start of the dashboard (POST /start) forgets the stop.
   * @example
   * refuseWhileStopped();
   */
  function refuseWhileStopped() {
    if (zigbee2mqttManager.stopped) {
      throw new BadParameters('Zigbee2mqtt: stopped by the user, start it instead');
    }
  }

  /**
   * @description Refuse to install or start anything until the service is started: not yet while Gladys starts its
   * services, nor once stopped in the settings, where Zigbee2mqtt would run with the service saved stopped and not
   * start again with Gladys. Settings > Services starts it.
   * @example
   * refuseUntilServiceStarted();
   */
  function refuseUntilServiceStarted() {
    if (!zigbee2mqttManager.serviceStarted) {
      throw new BadParameters('Zigbee2mqtt: the service is not started, start it in the settings first');
    }
  }

  /**
   * @api {get} /api/v1/service/zigbee2mqtt/discovered Get discovered Zigbee2mqtt devices
   * @apiName getDiscoveredDevices
   * @apiGroup Zigbee2mqtt
   */
  async function getDiscoveredDevices(req, res) {
    logger.debug('Get discovered devices');
    const { query = {} } = req;
    const defaultElectricMeterDeviceFeatureId = await gladys.energyPrice.getDefaultElectricMeterFeatureId();
    const devices = zigbee2mqttManager.getDiscoveredDevices(query, defaultElectricMeterDeviceFeatureId);
    res.json(devices);
  }

  /**
   * @api {get} /api/v1/service/zigbee2mqtt/adapter Get Zigbee2mqtt managed adapters
   * @apiName getManagerAdapters
   * @apiGroup Zigbee2mqtt
   */
  async function getManagedAdapters(req, res) {
    logger.debug('Get managed adapters');
    const response = zigbee2mqttManager.getManagedAdapters();
    res.json(response);
  }

  /**
   * @api {get} /api/v1/service/zigbee2mqtt/usb/port List serial ports, with the recognized coordinator model
   * @apiName getUsbPorts
   * @apiGroup Zigbee2mqtt
   */
  async function getUsbPorts(req, res) {
    logger.debug('Get USB ports');
    const response = await zigbee2mqttManager.getUsbPorts();
    res.json(response);
  }

  /**
   * @api {get} /api/v1/service/zigbee2mqtt/status Get Zigbee2mqtt connection status
   * @apiName status
   * @apiGroup Zigbee2mqtt
   */
  async function status(req, res) {
    logger.debug('Get status');
    const response = await zigbee2mqttManager.status();
    res.json(response);
  }

  /**
   * @api {get} /api/v1/service/zigbee2mqtt/setup Get current configuration
   * @apiName setup
   * @apiGroup Zigbee2mqtt
   */
  async function getCurrentSetup(req, res) {
    logger.debug('Getting current setup');
    const configuration = await zigbee2mqttManager.getSetup();
    res.json(configuration);
  }

  /**
   * @api {post} /api/v1/service/zigbee2mqtt/setup Setup
   * @apiName setup
   * @apiGroup Zigbee2mqtt
   */
  async function setup(req, res) {
    logger.debug('Entering setup step');
    refuseUntilServiceStarted();
    await zigbee2mqttManager.setup(req.body);
    const configuration = await zigbee2mqttManager.getSetup();
    res.json(configuration);
  }

  /**
   * @api {post} /api/v1/service/zigbee2mqtt/prefetch Download the missing images ahead of the installation
   * @apiName prefetch
   * @apiGroup Zigbee2mqtt
   */
  async function prefetch(req, res) {
    logger.debug('Prefetch the images');
    // Answers once the disk space is checked: the downloads go on in the background
    const response = await zigbee2mqttManager.startPrefetch();
    res.json(response);
  }

  /**
   * @api {post} /api/v1/service/zigbee2mqtt/connect Connect
   * @apiName connect
   * @apiGroup Zigbee2mqtt
   */
  async function connect(req, res) {
    logger.debug('Entering connect step');
    zigbee2mqttManager.refuseWhileInstalling('connect');
    refuseUntilServiceStarted();
    await zigbee2mqttManager.init();
    res.json({
      success: true,
    });
  }

  /**
   * @api {post} /api/v1/service/zigbee2mqtt/mqtt/start Install & start MQTT container.
   * @apiName installMqttContainer
   * @apiGroup Zigbee2mqtt
   */
  async function installMqttContainer(req, res) {
    logger.debug('Install MQTT container');
    // The broker accounts, also used to wait for the broker to answer
    const configuration = await zigbee2mqttManager.getConfiguration();
    // Once the configuration is read, with no wait until the broker is installed
    zigbee2mqttManager.refuseWhileInstalling('start the MQTT broker');
    refuseWhileStopped();
    refuseUntilServiceStarted();
    // Generated by the first init, which this route does not run
    if (!configuration.mqttPassword || !configuration.z2mMqttPassword) {
      throw new BadParameters('Zigbee2mqtt: the MQTT accounts do not exist yet, save the setup first');
    }
    await zigbee2mqttManager.installMqttContainer(configuration);
    res.json({
      success: true,
    });
  }

  /**
   * @api {post} /api/v1/service/zigbee2mqtt/z2m/start Install & start Z2M container.
   * @apiName installZ2mContainer
   * @apiGroup Zigbee2mqtt
   */
  async function installZ2mContainer(req, res) {
    logger.debug('Install Z2M container');
    // The coordinator passed to Zigbee2mqtt, and the broker account it connects with
    const configuration = await zigbee2mqttManager.getConfiguration();
    // Once the configuration is read, with no wait until Zigbee2mqtt is installed
    zigbee2mqttManager.refuseWhileInstalling('start Zigbee2mqtt');
    refuseWhileStopped();
    refuseUntilServiceStarted();
    // Saved by the setup: without it, the container would be created without a coordinator. The one of the adapter
    // mode, as init reads it.
    const { z2mAdapterMode, z2mDriverPath, z2mNetworkAdapterUrl } = configuration;
    const coordinator = z2mAdapterMode === ADAPTER_MODE.NETWORK ? z2mNetworkAdapterUrl : z2mDriverPath;
    if (!coordinator) {
      throw new BadParameters('Zigbee2mqtt: no Zigbee coordinator is configured yet, save the setup first');
    }
    await zigbee2mqttManager.installZ2mContainer(configuration);
    res.json({
      success: true,
    });
  }

  /**
   * @api {post} /api/v1/service/zigbee2mqtt/disconnect Disconnect
   * @apiName disconnect
   * @apiGroup Zigbee2mqtt
   */
  async function disconnect(req, res) {
    logger.debug('Entering disconnect step');
    zigbee2mqttManager.refuseWhileInstalling('disconnect');
    await zigbee2mqttManager.disconnect();
    res.json({
      success: true,
    });
  }

  /**
   * @api {post} /api/v1/service/zigbee2mqtt/permit_join Allow, forbid or toggle permit_join Zigbee devices
   * @apiName togglePermitJoin
   * @apiGroup Zigbee2mqtt
   * @apiBody {boolean} [value] true to allow, false to forbid; toggles when absent
   */
  async function togglePermitJoin(req, res) {
    const { value } = req.body || {};
    if (value !== undefined && typeof value !== 'boolean') {
      throw new BadParameters('Zigbee2mqtt: permit_join value must be a boolean');
    }
    logger.debug('Set permit_join', value);
    await zigbee2mqttManager.setPermitJoin(value);
    res.json({
      success: true,
    });
  }

  /**
   * @api {post} /api/v1/service/zigbee2mqtt/run/stop Stop Zigbee2mqtt until it is started again. Not
   * /api/v1/service/zigbee2mqtt/stop: that one is the route of the core that stops the service (Settings > Services)
   * @apiName stop
   * @apiGroup Zigbee2mqtt
   */
  async function stop(req, res) {
    logger.debug('Stopping Zigbee2mqtt');
    await zigbee2mqttManager.stop();
    res.json({
      success: true,
    });
  }

  /**
   * @api {post} /api/v1/service/zigbee2mqtt/run/start Start Zigbee2mqtt again, in the background
   * @apiName start
   * @apiGroup Zigbee2mqtt
   */
  async function start(req, res) {
    logger.debug('Starting Zigbee2mqtt');
    refuseUntilServiceStarted();
    await zigbee2mqttManager.start();
    res.json({
      success: true,
    });
  }

  /**
   * @api {post} /api/v1/service/zigbee2mqtt/run/restart Restart Zigbee2mqtt
   * @apiName restart
   * @apiGroup Zigbee2mqtt
   */
  async function restart(req, res) {
    logger.debug('Restarting Zigbee2mqtt');
    refuseUntilServiceStarted();
    await zigbee2mqttManager.restart();
    res.json({
      success: true,
    });
  }

  /**
   * @api {post} /api/v1/service/zigbee2mqtt/reset Reset Zigbee2mqtt integration
   * @apiName reset
   * @apiGroup Zigbee2mqtt
   */
  async function reset(req, res) {
    logger.debug('Entering reset step');
    zigbee2mqttManager.refuseWhileInstalling('reset');
    await zigbee2mqttManager.reset();
    res.json({
      success: true,
    });
  }

  /**
   * @api {get} /api/v1/service/zigbee2mqtt/permit_join Get permit_join status
   * @apiName getPermitJoin
   * @apiGroup Zigbee2mqtt
   */
  async function getPermitJoin(req, res) {
    logger.debug('Get permit_join');
    const response = zigbee2mqttManager.getPermitJoin();
    res.json(response);
  }

  /**
   * @api {get} /api/v1/service/zigbee2mqtt/pairing Get the devices seen joining since joining last opened
   * @apiName getPairingDevices
   * @apiGroup Zigbee2mqtt
   */
  async function getPairingDevices(req, res) {
    const defaultElectricMeterDeviceFeatureId = await gladys.energyPrice.getDefaultElectricMeterFeatureId();
    res.json(zigbee2mqttManager.getPairingDevices(defaultElectricMeterDeviceFeatureId));
  }

  return {
    'get /api/v1/service/zigbee2mqtt/discovered': {
      authenticated: true,
      controller: asyncMiddleware(getDiscoveredDevices),
    },
    'get /api/v1/service/zigbee2mqtt/adapter': {
      authenticated: true,
      controller: asyncMiddleware(getManagedAdapters),
    },
    'get /api/v1/service/zigbee2mqtt/usb/port': {
      authenticated: true,
      controller: asyncMiddleware(getUsbPorts),
    },
    'get /api/v1/service/zigbee2mqtt/status': {
      authenticated: true,
      controller: asyncMiddleware(status),
    },
    // the setup holds the MQTT broker credentials Zigbee2mqtt connects with
    // (GLADYS_MQTT_PASSWORD among them) and hands them straight to res.json()
    'get /api/v1/service/zigbee2mqtt/setup': {
      authenticated: true,
      admin: true,
      controller: asyncMiddleware(getCurrentSetup),
    },
    'post /api/v1/service/zigbee2mqtt/setup': {
      authenticated: true,
      admin: true,
      controller: asyncMiddleware(setup),
    },
    // downloads the images of the installation, more than 200 MB on the disk of Gladys
    'post /api/v1/service/zigbee2mqtt/prefetch': {
      authenticated: true,
      admin: true,
      controller: asyncMiddleware(prefetch),
    },
    'post /api/v1/service/zigbee2mqtt/connect': {
      authenticated: true,
      controller: asyncMiddleware(connect),
    },
    'post /api/v1/service/zigbee2mqtt/mqtt/start': {
      authenticated: true,
      controller: asyncMiddleware(installMqttContainer),
    },
    'post /api/v1/service/zigbee2mqtt/z2m/start': {
      authenticated: true,
      controller: asyncMiddleware(installZ2mContainer),
    },
    'post /api/v1/service/zigbee2mqtt/disconnect': {
      authenticated: true,
      controller: asyncMiddleware(disconnect),
    },
    'post /api/v1/service/zigbee2mqtt/permit_join': {
      authenticated: true,
      controller: asyncMiddleware(togglePermitJoin),
    },
    'get /api/v1/service/zigbee2mqtt/permit_join': {
      authenticated: true,
      controller: asyncMiddleware(getPermitJoin),
    },
    'get /api/v1/service/zigbee2mqtt/pairing': {
      authenticated: true,
      controller: asyncMiddleware(getPairingDevices),
    },
    // Under run/: /api/v1/service/zigbee2mqtt/start and /stop are the routes of the core that start and stop the
    // service (Settings > Services), which a route of the integration registered first would hide
    'post /api/v1/service/zigbee2mqtt/run/stop': {
      authenticated: true,
      admin: true,
      controller: asyncMiddleware(stop),
    },
    'post /api/v1/service/zigbee2mqtt/run/start': {
      authenticated: true,
      admin: true,
      controller: asyncMiddleware(start),
    },
    'post /api/v1/service/zigbee2mqtt/run/restart': {
      authenticated: true,
      admin: true,
      controller: asyncMiddleware(restart),
    },
    'post /api/v1/service/zigbee2mqtt/reset': {
      authenticated: true,
      admin: true,
      controller: asyncMiddleware(reset),
    },
  };
};
