/**
 * @description Whether a 2-letter code is a region TMDB actually recognizes.
 * @param {string} code - The candidate region code (ex. 'FR').
 * @returns {boolean} True if TMDB's own /configuration/countries list includes it.
 * @example
 * isAssignedRegion('FR'); // true
 * isAssignedRegion('EU'); // false — a grouping, not a country TMDB tracks
 * isAssignedRegion('ZZ'); // false — not a real code at all
 */
function isAssignedRegion(code) {
  return REGION_PATTERN.test(code) && TMDB_REGIONS.has(code);
}

